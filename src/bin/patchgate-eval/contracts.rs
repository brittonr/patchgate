fn setup_contracts(dir: &Path, signer: &Signer) -> Result<Value> {
    let repo = start(
        dir,
        signer,
        &[
            ("POLICY.md", POLICY),
            ("Cargo.toml", MANIFEST),
            ("Cargo.lock", LOCK),
            ("src/lib.rs", LIB),
            ("src/main.rs", ENTRY),
            ("src/amount.rs", AMOUNT),
            ("src/api.rs", API),
            ("src/error.rs", ERROR),
        ],
    )?;
    let base = repo.hashes("main")?;
    let quote = API.replace("pub fn currency()", &format!("{QUOTE}pub fn currency()"));
    let parse = API.replace(
        "pub fn currency()",
        &format!("{PARSE_QUOTE}pub fn currency()"),
    );
    let amount = AMOUNT.replace("checked_mul(2)", "checked_mul(3)");
    let errors = ERROR.replace(
        "\"invalid units\"",
        "\"units must be an unsigned decimal integer\"",
    );
    let (quote, parse) = concurrent(
        &repo,
        &[("src/api.rs", &quote), ("src/amount.rs", &amount)],
        "Add the numeric quote API and correct the unit rate",
        &[("src/api.rs", &parse), ("src/error.rs", &errors)],
        "Add the text quote API and its public error message",
    )?;
    ensure!(
        repo.archive("inbox")?.messages.contains("Order conflict"),
        "The API fixture must contain a real order conflict."
    );
    Ok(json!({"base": base, "quote": quote, "parse": parse}))
}

