#[test]
fn module_interfaces_share_one_public_result_contract() {
    let _: fn(u64) -> Result<u64, Error> = quote;
    let _: fn(&str) -> Result<u64, Error> = parse_quote;
    assert_eq!(currency(), "USD");
    for units in [0, 1, 2, 19, 4096, u64::MAX / 3] {
        let expected = units.checked_mul(3).ok_or(Error::Overflow);
        assert_eq!(quote(units), expected);
        assert_eq!(Units::new(units).cents(), expected);
        assert_eq!(parse_quote(&format!("  {units}\n")), expected);
    }
}

#[test]
fn numeric_boundaries_do_not_wrap_or_saturate() {
    let last = u64::MAX / 3;
    assert_eq!(quote(last), Ok(u64::MAX));
    for units in [last + 1, u64::MAX - 1, u64::MAX] {
        assert_eq!(quote(units), Err(Error::Overflow));
        assert_eq!(Units::new(units).cents(), Err(Error::Overflow));
        assert_eq!(parse_quote(&units.to_string()), Err(Error::Overflow));
    }
    assert_eq!(parse_quote("18446744073709551616"), Err(Error::InvalidUnits));
}

#[test]
fn callers_receive_stable_error_variants_and_messages() {
    for input in ["", " ", "\t\n"] {
        assert_eq!(parse_quote(input), Err(Error::Empty));
    }
    for input in ["-1", "3.5", "1 2", "1_000", "USD 3", "NaN"] {
        assert_eq!(parse_quote(input), Err(Error::InvalidUnits));
    }
    assert_eq!(parse_quote("0002"), Ok(6));
    for (error, message) in [
        (Error::Empty, "units are empty"),
        (Error::InvalidUnits, "units must be an unsigned decimal integer"),
        (Error::Overflow, "numeric overflow"),
    ] {
        assert_eq!(public_error(&error), message);
    }
}
