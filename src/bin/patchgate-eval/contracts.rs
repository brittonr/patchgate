fn scripted_review(repo: &Repo, choice: &'static str) -> Result<()> {
    let model = ModelServer::new(move |request| {
        if request.path != "/v1/chat/completions" {
            return Reply {
                status: 404,
                body: json!({"error": "unknown endpoint"}),
            };
        }
        if request
            .body
            .pointer("/response_format/json_schema/name")
            .and_then(Value::as_str)
            == Some("merge")
        {
            chat_reply(
                json!({"choice": choice, "reason": "Preserve the public Rust contracts within the bounded choices."}),
            )
        } else {
            chat_reply(verdict("accept"))
        }
    })?;
    checked_output(
        repo.gate(Some(&model), &["review"], &[])?,
        "Review the Rust fixture",
    )?;
    Ok(())
}

fn solve_contracts(dir: &Path, _options: &RunOptions) -> Result<()> {
    scripted_review(&Repo::open(dir.join("repo")), "both, side 1 first")
}

fn solve_errors_order(dir: &Path, _options: &RunOptions) -> Result<()> {
    let signer = Signer::new()?;
    let repo = Repo {
        path: dir.join("repo"),
        env: Arc::clone(&signer.env),
    };
    scripted_review(&repo, "escalate")?;
    let facts = load_facts(dir)?;
    let scale = facts["scale"]
        .as_str()
        .context("The scale hash is absent.")?;
    let records = repo.ledger()?;
    ensure!(
        records.iter().any(|record| record["hash"] == scale
            && record["decision"] == "escalate"
            && record["by"] == "gate"
            && record["conflict"] == true),
        "The nested Account conflict must require a human decision."
    );
    ensure!(
        !repo.hashes("main")?.contains(scale),
        "The unresolved scale change must remain outside main."
    );
    let resolved = format!(
        "{}{}",
        SETTLEMENT.replace(
            "        Ok(balance)",
            "        balance.checked_mul(self.factor).ok_or(Error::Overflow)"
        ),
        ORDER_POLICY,
    );
    let resolution = repo.change(&[("src/settlement.rs", &resolved)], HUMAN_MESSAGE)?;
    checked_output(
        repo.gate(
            None,
            &["accept", &resolution, "--reason", HUMAN_REASON],
            &[("USER", HUMAN_USER)],
        )?,
        "Accept the recorded Account resolution",
    )?;
    Ok(())
}

fn base_hashes(check: &Check, candidates: &[&str]) -> Result<BTreeSet<String>> {
    let mut hashes = BTreeSet::new();
    for hash in check.facts["base"]
        .as_array()
        .context("The base hashes are absent.")?
    {
        hashes.insert(hash.as_str().context("A base hash is invalid.")?.to_owned());
    }
    for name in candidates {
        hashes.insert(
            check.facts[*name]
                .as_str()
                .context("A candidate hash is absent.")?
                .to_owned(),
        );
    }
    Ok(hashes)
}

fn exact_channels(check: &mut Check, expected: &BTreeSet<String>) -> Result<()> {
    for channel in ["main", "inbox"] {
        check.require(
            check.repo.hashes(channel)? == *expected,
            format!("{channel} must contain the exact base, candidate, and resolution hashes."),
        );
        check.no_conflicts(channel)?;
    }
    Ok(())
}

fn check_contracts(check: &mut Check) -> Result<()> {
    let ledger = check.repo.ledger()?;
    let mut expected = base_hashes(check, &["quote", "parse"])?;
    let mut accepted = Vec::new();
    for name in ["quote", "parse"] {
        let records = check.records(name)?;
        check.require(
            matches!(records.as_slice(), [record] if record["decision"] == "accept" && record["by"] == "model" && record["model"] == "harbor-scripted"),
            format!("{name} must have one scripted model acceptance."),
        );
        accepted.extend(records);
    }
    let merges: Vec<_> = ledger
        .iter()
        .filter(|record| record["decision"] == "merge")
        .collect();
    check.require(
        ledger.len() == 3 && merges.len() == 1,
        "The audit must contain two acceptances and one merge.",
    );
    if let [merge] = merges.as_slice() {
        let hash = merge["hash"].as_str().unwrap_or("");
        check.require(
            !hash.is_empty() && !expected.contains(hash),
            "The merge must have a separate recorded hash.",
        );
        check.require(
            merge["by"] == "model"
                && merge["model"] == "harbor-scripted"
                && merge["files"] == json!(["src/api.rs"]),
            "The merge audit must identify its model and API file.",
        );
        let linked: Vec<_> = accepted
            .iter()
            .filter(|record| record["merge"].as_str() == Some(hash))
            .collect();
        check.require(
            linked.len() == 1,
            "Exactly one candidate acceptance must link to the actual merge hash.",
        );
        if let [review] = linked.as_slice() {
            check.require(
                merge["for"] == json!([review["hash"]]),
                "The merge audit must link to the exact candidate hash.",
            );
            let review_index = ledger.iter().position(|record| record == *review);
            let merge_index = ledger.iter().position(|record| record == *merge);
            check.require(
                matches!((review_index, merge_index), (Some(a), Some(b)) if a < b),
                "The acceptance must precede its linked merge audit.",
            );
        }
        expected.insert(hash.to_owned());
    }
    exact_channels(check, &expected)?;
    check_program(check, CONTRACT_TESTS, false)
}

fn check_errors_order(check: &mut Check) -> Result<()> {
    let policy = check.records("policy")?;
    check.require(matches!(policy.as_slice(), [record] if record["decision"] == "accept" && record["by"] == "model" && record["model"] == "harbor-scripted"), "The policy candidate must have one scripted model acceptance.");
    let scale = check.records("scale")?;
    check.require(
        matches!(scale.as_slice(), [escalation, acceptance]
            if escalation["decision"] == "escalate" && escalation["by"] == "gate"
                && escalation["conflict"] == true && acceptance["decision"] == "accept"
                && acceptance["by"] == "human" && acceptance["user"] == HUMAN_USER),
        "The scale candidate must require escalation and explicit human acceptance.",
    );
    let mut expected = base_hashes(check, &["policy", "scale"])?;
    let main = check.repo.hashes("main")?;
    let resolutions: Vec<_> = main.difference(&expected).cloned().collect();
    check.require(
        resolutions.len() == 1,
        "The owner must record one separate resolution hash.",
    );
    let ledger = check.repo.ledger()?;
    check.require(
        ledger.len() == 4,
        "The audit must contain one model acceptance, one escalation, and two human acceptances.",
    );
    if let [hash] = resolutions.as_slice() {
        let resolution: Vec<_> = ledger
            .iter()
            .filter(|record| record["hash"] == *hash)
            .collect();
        check.require(
            matches!(resolution.as_slice(), [record] if record["decision"] == "accept"
                && record["by"] == "human" && record["user"] == HUMAN_USER
                && record["reason"] == HUMAN_REASON && record["message"] == HUMAN_MESSAGE
                && record.get("merge").is_none()),
            "The exact resolution hash must have one human audit with the owner, message, and reason.",
        );
        if let Some(acceptance) = scale.last() {
            let linked_reason = format!(
                "{HUMAN_REASON} It lands with {}.",
                &hash[..hash.len().min(12)]
            );
            check.require(
                acceptance["reason"] == linked_reason && acceptance.get("merge").is_none(),
                "The scale acceptance must identify the actual human resolution.",
            );
        }
        let actual = check.repo.pijul(&["change", hash])?;
        check.require(
            actual.contains(HUMAN_MESSAGE),
            "The resolution message must match the actual Pijul change.",
        );
        expected.insert(hash.clone());
    }
    exact_channels(check, &expected)?;
    check_program(check, ORDER_TESTS, true)
}

fn check_program(check: &mut Check, tests: &str, order: bool) -> Result<()> {
    let expected_files: BTreeSet<&str> = if order {
        [
            "POLICY.md",
            "Cargo.toml",
            "Cargo.lock",
            "src/lib.rs",
            "src/main.rs",
            "src/settlement.rs",
            "src/error.rs",
        ]
        .into_iter()
        .collect()
    } else {
        [
            "POLICY.md",
            "Cargo.toml",
            "Cargo.lock",
            "src/lib.rs",
            "src/main.rs",
            "src/amount.rs",
            "src/api.rs",
            "src/error.rs",
        ]
        .into_iter()
        .collect()
    };
    for channel in ["main", "inbox"] {
        let snapshot = check.repo.archive(channel)?;
        let actual_files: BTreeSet<_> = snapshot.files.keys().map(String::as_str).collect();
        check.require(
            actual_files == expected_files,
            format!("{channel} must retain the exact fixture file set."),
        );
        for (path, text) in [
            ("POLICY.md", POLICY),
            ("Cargo.toml", MANIFEST),
            ("Cargo.lock", LOCK),
            ("src/lib.rs", if order { ORDER_LIB } else { LIB }),
            ("src/main.rs", if order { ORDER_ENTRY } else { ENTRY }),
        ] {
            check.require(
                snapshot.files.get(path).map(Vec::as_slice) == Some(text.as_bytes()),
                format!("{channel} must preserve {path}."),
            );
        }
        let directory = tempfile::tempdir()?;
        let source = directory.path().join("source");
        fs::create_dir(&source)?;
        for (path, bytes) in &snapshot.files {
            ensure!(
                Path::new(path)
                    .components()
                    .all(|component| matches!(component, std::path::Component::Normal(_))),
                "The fixture archive path is unsafe."
            );
            let target = source.join(path);
            if let Some(parent) = target.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(target, bytes)?;
        }
        let library = directory.path().join("libharbor_contract_fixture.rlib");
        let output = Command::new("rustc")
            .args([
                "--edition=2021",
                "--crate-name",
                "harbor_contract_fixture",
                "--crate-type=rlib",
            ])
            .arg(source.join("src/lib.rs"))
            .arg("-o")
            .arg(&library)
            .current_dir(directory.path())
            .output()
            .context("Cannot compile the channel library.")?;
        let compiled = output.status.success();
        check.require(
            compiled,
            format!(
                "{channel} must compile its Rust modules.\n{}",
                String::from_utf8_lossy(&output.stderr)
            ),
        );
        if !compiled {
            continue;
        }
        let harness = directory.path().join("verifier.rs");
        fs::write(&harness, tests)?;
        let executable = directory.path().join("verifier");
        let external = format!("harbor_contract_fixture={}", library.display());
        let output = Command::new("rustc")
            .args(["--edition=2021", "--test"])
            .arg(&harness)
            .arg("--extern")
            .arg(&external)
            .arg("-o")
            .arg(&executable)
            .current_dir(directory.path())
            .output()
            .context("Cannot compile the independent consumer tests.")?;
        let compiled = output.status.success();
        check.require(
            compiled,
            format!(
                "{channel} must expose the required public Rust interface.\n{}",
                String::from_utf8_lossy(&output.stderr)
            ),
        );
        if !compiled {
            continue;
        }
        let output = Command::new(executable)
            .arg("--test-threads=1")
            .current_dir(directory.path())
            .output()
            .context("Cannot execute the independent consumer tests.")?;
        check.require(
            output.status.success(),
            format!(
                "{channel} must pass the verifier-owned behavior assertions.\n{}\n{}",
                String::from_utf8_lossy(&output.stdout),
                String::from_utf8_lossy(&output.stderr)
            ),
        );
        let executable = directory.path().join("consumer");
        let output = Command::new("rustc")
            .arg("--edition=2021")
            .arg(source.join("src/main.rs"))
            .arg("--extern")
            .arg(&external)
            .arg("-o")
            .arg(&executable)
            .current_dir(directory.path())
            .output()
            .context("Cannot compile the fixture executable.")?;
        let compiled = output.status.success();
        check.require(
            compiled,
            format!(
                "{channel} must compile the fixture executable.\n{}",
                String::from_utf8_lossy(&output.stderr)
            ),
        );
        if compiled {
            let output = Command::new(executable)
                .current_dir(directory.path())
                .output()
                .context("Cannot execute the fixture consumer.")?;
            check.require(
                output.status.success(),
                format!(
                    "{channel} must execute its consumer assertions.\n{}",
                    String::from_utf8_lossy(&output.stderr)
                ),
            );
        }
    }
    Ok(())
}
