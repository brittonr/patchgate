#[test]
fn public_interface_retains_both_author_contributions() {
    let _: fn(Account) -> Result<u64, Error> = Account::settle;
    assert_eq!(settlement_policy(), "debit-before-scale");
    assert_eq!(result(23, 7, 3), Ok(48));
    assert_eq!(result(8, 3, 2), Ok(10));
    assert_eq!(result(8, 3, 0), Ok(0));
    assert_eq!(result(0, 0, 9), Ok(0));
}

#[test]
fn debit_precedes_scale_at_numeric_boundaries() {
    assert_eq!(result(u64::MAX, u64::MAX, 2), Ok(0));
    assert_eq!(result(u64::MAX, u64::MAX - 1, u64::MAX), Ok(u64::MAX));
    assert_eq!(result(u64::MAX, 0, 1), Ok(u64::MAX));
    assert_eq!(result(u64::MAX / 2 + 1, 1, 2), Ok(u64::MAX - 1));
    assert_eq!(result(u64::MAX / 2 + 1, 0, 2), Err(Error::Overflow));
    assert_eq!(result(u64::MAX, 0, 2), Err(Error::Overflow));
}

#[test]
fn public_errors_preserve_precedence_payload_and_display() {
    for (available, requested, factor) in [(0, 1, 0), (3, 4, u64::MAX), (u64::MAX - 1, u64::MAX, 2)] {
        let expected = Error::Insufficient { available, requested };
        let actual = result(available, requested, factor).unwrap_err();
        assert_eq!(actual, expected);
        assert_eq!(actual.to_string(), format!("debit {requested} exceeds balance {available}"));
        let public: &(dyn std::error::Error + Send + Sync) = &actual;
        assert!(public.source().is_none());
    }
    assert_eq!(Error::Overflow.to_string(), "settlement exceeds u64");
    assert_eq!(result(7, 7, u64::MAX), Ok(0));
}
