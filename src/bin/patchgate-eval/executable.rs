const MANIFEST: &str = "[package]\nname = \"harbor-rust-fixture\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[workspace]\n";
const LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"harbor-rust-fixture\"\nversion = \"0.1.0\"\n";

const BEHAVIOR_BASE: &str = r#"pub fn contributions() -> Vec<&'static str> {
    let mut events = vec!["start"];
    events.push("end");
    events
}
"#;
const BEHAVIOR_MAIN: &str = r#"fn main() {
    println!("{}", harbor_rust_fixture::contributions().join(","));
}
"#;
const BEHAVIOR_TESTS: &str = r#"use harbor_rust_fixture::contributions;

#[test]
fn both_contributions_survive_in_either_order() {
    let events = contributions();
    assert_eq!(events.len(), 4, "Each contribution must occur once.");
    assert_eq!(events.first(), Some(&"start"));
    assert_eq!(events.last(), Some(&"end"));
    assert!(events[1..3] == ["alpha", "beta"] || events[1..3] == ["beta", "alpha"]);
}

#[test]
fn calls_produce_independent_results() {
    let mut first = contributions();
    first.clear();
    let second = contributions();
    assert_eq!(second.len(), 4);
    assert_eq!(second.iter().filter(|event| **event == "alpha").count(), 1);
    assert_eq!(second.iter().filter(|event| **event == "beta").count(), 1);
}
"#;

const BUILD_BASE: &str = r#"pub struct Parcel {
    pub weight: u64,
    pub zones: u64,
}

impl Parcel {
    pub fn shipping_cost(&self) -> u64 {
        let cost = self.weight * 2;
        cost + self.zones
    }
}

pub fn label() -> &'static str {
    "parcel"
}
"#;
const BUILD_BLOCK: &str = r#"impl Parcel {
    pub fn shipping_cost(&self) -> u64 {
        let cost = self.weight * 2;
        cost + self.zones
    }
}

"#;
const BUILD_ROUTE: &str = r#"
pub fn route_label() -> &'static str {
    "tracked"
}
"#;
const BUILD_MAIN: &str = r#"fn main() {
    println!("{}", harbor_rust_fixture::label());
}
"#;
const BUILD_TESTS: &str = r#"use harbor_rust_fixture::{label, route_label, Parcel};

#[test]
fn restored_impl_uses_the_new_rate() {
    for (weight, zones, expected) in [(0, 0, 0), (0, 7, 7), (1, 0, 3), (4, 2, 14), (19, 5, 62)] {
        assert_eq!(Parcel { weight, zones }.shipping_cost(), expected);
    }
}

#[test]
fn both_author_contributions_survive() {
    assert_eq!(route_label(), "tracked");
    assert_eq!(label(), "parcel");
    let parcel = Parcel { weight: 8, zones: 3 };
    assert_eq!(format!("{}:{}:{}", label(), route_label(), parcel.shipping_cost()), "parcel:tracked:27");
}
"#;

fn fixture(dir: &Path, signer: &Signer, library: &str, main: &str) -> Result<Repo> {
    start(
        dir,
        signer,
        &[
            ("POLICY.md", POLICY),
            ("Cargo.toml", MANIFEST),
            ("Cargo.lock", LOCK),
            ("src/lib.rs", library),
            ("src/main.rs", main),
        ],
    )
}

fn setup_behavior(dir: &Path, signer: &Signer) -> Result<Value> {
    let repo = fixture(dir, signer, BEHAVIOR_BASE, BEHAVIOR_MAIN)?;
    let base = repo.hashes("main")?;
    let alpha = BEHAVIOR_BASE.replace(
        "    events.push(\"end\");",
        "    events.push(\"alpha\");\n    events.push(\"end\");",
    );
    let beta = BEHAVIOR_BASE.replace(
        "    events.push(\"end\");",
        "    events.push(\"beta\");\n    events.push(\"end\");",
    );
    let (alpha, beta) = concurrent(
        &repo,
        &[("src/lib.rs", &alpha)],
        "Add the alpha contribution",
        &[("src/lib.rs", &beta)],
        "Add the beta contribution",
    )?;
    ensure!(
        repo.archive("inbox")?.messages.contains("Order conflict"),
        "The behavior fixture must contain a real order conflict."
    );
    Ok(json!({"base": base, "alpha": alpha, "beta": beta}))
}

fn setup_build(dir: &Path, signer: &Signer) -> Result<Value> {
    let repo = fixture(dir, signer, BUILD_BASE, BUILD_MAIN)?;
    let base = repo.hashes("main")?;
    let removal = format!("{}{}", BUILD_BASE.replace(BUILD_BLOCK, ""), BUILD_ROUTE);
    let rate = BUILD_BASE.replace("self.weight * 2", "self.weight * 3");
    let (route, rate) = concurrent(
        &repo,
        &[("src/lib.rs", &removal)],
        "Remove the old cost implementation and add the route label",
        &[("src/lib.rs", &rate)],
        "Correct the shipping rate",
    )?;
    ensure!(
        repo.archive("inbox")?
            .messages
            .contains("Deletion conflict"),
        "The build fixture must contain a real deletion conflict."
    );
    Ok(json!({"base": base, "route": route, "rate": rate}))
}

fn solve_behavior(dir: &Path, options: &RunOptions) -> Result<()> {
    solve(dir, options, "both, side 1 first")
}

fn solve_build(dir: &Path, options: &RunOptions) -> Result<()> {
    solve(dir, options, "escalate")?;
    let facts = load_facts(dir)?;
    let signer = Signer::new()?;
    let repo = Repo {
        path: dir.join("repo"),
        env: Arc::clone(&signer.env),
    };
    let rate = facts["rate"].as_str().context("The rate hash is absent.")?;
    let history = repo.ledger()?;
    ensure!(
        history.iter().any(|record| record["hash"] == rate
            && record["decision"] == "escalate"
            && record["by"] == "gate"
            && record["conflict"] == true),
        "The nested conflict must require a human decision."
    );
    ensure!(
        !repo.hashes("main")?.contains(rate),
        "The unresolved rate change must remain outside main."
    );
    let resolved = format!(
        "{}{}",
        BUILD_BASE.replace("self.weight * 2", "self.weight * 3"),
        BUILD_ROUTE
    );
    let resolution = repo.change(
        &[("src/lib.rs", &resolved)],
        "Restore the complete Parcel implementation with the corrected rate",
    )?;
    checked_output(
        repo.gate(
            None,
            &[
                "accept",
                &resolution,
                "--reason",
                "The owner restores the complete implementation and preserves the route label.",
            ],
            &[],
        )?,
        "Accept the human Rust resolution.",
    )?;
    Ok(())
}

fn solve(dir: &Path, options: &RunOptions, choice: &'static str) -> Result<()> {
    let repo = Repo::open(dir.join("repo"));
    let output = if let Some(url) = options.model_url.as_deref() {
        repo.gate(
            None,
            &["review"],
            &[
                ("PATCHGATE_MODEL_URL", url),
                ("PATCHGATE_MODEL", &options.model),
                ("PATCHGATE_MODEL_API", &options.api),
            ],
        )?
    } else {
        let model = ModelServer::new(move |request| {
            if request
                .body
                .pointer("/response_format/json_schema/name")
                .and_then(Value::as_str)
                == Some("merge")
            {
                chat_reply(
                    json!({"choice": choice, "reason": "Retain both author contributions and the complete Rust structure."}),
                )
            } else {
                chat_reply(verdict("accept"))
            }
        })?;
        repo.gate(Some(&model), &["review"], &[])?
    };
    checked_output(output, "The Rust fixture review must succeed.")?;
    Ok(())
}

fn check_behavior(check: &mut Check) -> Result<()> {
    check_merge(check, &["alpha", "beta"])?;
    check_program(check, BEHAVIOR_TESTS, true)
}

fn check_build(check: &mut Check) -> Result<()> {
    let route = check.records("route")?;
    check.require(
        matches!(route.as_slice(), [record] if record["decision"] == "accept" && record["by"] == "model"),
        "The route change must have one model acceptance.",
    );
    let rate = check.records("rate")?;
    check.require(
        matches!(rate.as_slice(), [escalation, acceptance]
            if escalation["decision"] == "escalate"
                && escalation["by"] == "gate"
                && escalation["conflict"] == true
                && acceptance["decision"] == "accept"
                && acceptance["by"] == "human"),
        "The nested conflict must require escalation and human acceptance.",
    );
    let mut expected = BTreeSet::new();
    for value in check.facts["base"]
        .as_array()
        .context("The base hashes are absent.")?
    {
        expected.insert(
            value
                .as_str()
                .context("A base hash is invalid.")?
                .to_owned(),
        );
    }
    for name in ["route", "rate"] {
        expected.insert(
            check.facts[name]
                .as_str()
                .context("A candidate hash is absent.")?
                .to_owned(),
        );
    }
    let main = check.repo.hashes("main")?;
    let resolutions: Vec<_> = main.difference(&expected).cloned().collect();
    check.require(
        resolutions.len() == 1,
        "The human resolution must have one separate change hash.",
    );
    let ledger = check.repo.ledger()?;
    check.require(
        ledger.len() == 4,
        "The ledger must contain the model review, escalation, and two human acceptances.",
    );
    if let [resolution] = resolutions.as_slice() {
        check.require(
            ledger
                .iter()
                .filter(|record| record["hash"] == *resolution)
                .count()
                == 1
                && ledger.iter().any(|record| {
                    record["hash"] == *resolution
                        && record["decision"] == "accept"
                        && record["by"] == "human"
                        && record["user"].as_str().is_some_and(|user| !user.is_empty())
                }),
            "The resolution must have exactly one human acceptance with an actor.",
        );
        expected.insert(resolution.clone());
    }
    for channel in ["main", "inbox"] {
        check.within(channel, &["route", "rate"])?;
        check.no_conflicts(channel)?;
        check.require(
            check.repo.hashes(channel)? == expected,
            format!(
                "{channel} must contain only the base, both candidates, and the human resolution."
            ),
        );
    }
    check_program(check, BUILD_TESTS, false)
}

fn check_merge(check: &mut Check, names: &[&str]) -> Result<()> {
    for channel in ["main", "inbox"] {
        check.within(channel, names)?;
        check.no_conflicts(channel)?;
    }
    let mut accepted = Vec::new();
    for name in names {
        check.decision(name, "accept", "model")?;
        let records = check.records(name)?;
        check.require(
            records.len() == 1 && records[0]["decision"] == "accept" && records[0]["by"] == "model",
            format!("{name} must have one accepted model review."),
        );
        accepted.extend(records);
    }
    let ledger = check.repo.ledger()?;
    let merges: Vec<_> = ledger
        .iter()
        .filter(|record| record["decision"] == "merge")
        .collect();
    check.require(
        ledger.len() == 3 && merges.len() == 1,
        "The ledger must contain two reviews and one real merge record.",
    );
    let Some(merge) = merges.first() else {
        return Ok(());
    };
    check.require(
        merge["by"] == "model",
        "The model must own the merge record.",
    );
    check.require(
        merge["files"] == json!(["src/lib.rs"]),
        "The merge must identify src/lib.rs.",
    );
    let hash = merge["hash"].as_str().unwrap_or("");
    let linked: Vec<_> = accepted
        .iter()
        .filter(|record| record["merge"].as_str() == Some(hash))
        .collect();
    check.require(
        linked.len() == 1,
        "One accepted review must link to the real merge hash.",
    );
    if let Some(review) = linked.first() {
        check.require(
            merge["for"] == json!([review["hash"]]),
            "The merge must identify its accepted candidate.",
        );
        let review_position = ledger.iter().position(|record| record == *review);
        let merge_position = ledger.iter().position(|record| record == *merge);
        check.require(
            matches!((review_position, merge_position), (Some(a), Some(b)) if a < b),
            "The accepted review must precede its merge record.",
        );
    }
    let mut expected = BTreeSet::new();
    for value in check.facts["base"]
        .as_array()
        .context("The base hashes are absent.")?
    {
        expected.insert(
            value
                .as_str()
                .context("A base hash is invalid.")?
                .to_owned(),
        );
    }
    for name in names {
        expected.insert(
            check.facts[*name]
                .as_str()
                .context("A candidate hash is absent.")?
                .to_owned(),
        );
    }
    check.require(
        !hash.is_empty() && !expected.contains(hash),
        "The merge must have a separate recorded hash.",
    );
    expected.insert(hash.to_owned());
    for channel in ["main", "inbox"] {
        let actual = check.repo.hashes(channel)?;
        check.require(
            actual == expected,
            format!("{channel} must contain both candidates and the real merge change."),
        );
    }
    Ok(())
}

fn check_program(check: &mut Check, tests: &str, behavior: bool) -> Result<()> {
    for channel in ["main", "inbox"] {
        let snapshot = check.repo.archive(channel)?;
        let directory = tempfile::tempdir()?;
        for (path, bytes) in &snapshot.files {
            ensure!(
                Path::new(path)
                    .components()
                    .all(|component| matches!(component, std::path::Component::Normal(_))),
                "unsafe fixture archive path"
            );
            let target = directory.path().join(path);
            if let Some(parent) = target.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(target, bytes)?;
        }
        fs::create_dir_all(directory.path().join("tests"))?;
        fs::write(directory.path().join("tests/harbor.rs"), tests)?;
        let output = Command::new("cargo")
            .args([
                "test",
                "--offline",
                "--locked",
                "--all-targets",
                "--",
                "--test-threads=1",
            ])
            .current_dir(directory.path())
            .env("CARGO_TARGET_DIR", directory.path().join("target"))
            .output()
            .context("Cannot execute the offline Rust fixture tests.")?;
        let tests_pass = output.status.success();
        check.require(
            tests_pass,
            format!(
                "{channel} must compile and pass the Rust behavior tests.\n{}\n{}",
                String::from_utf8_lossy(&output.stdout),
                String::from_utf8_lossy(&output.stderr),
            ),
        );
        if !tests_pass {
            continue;
        }
        let output = Command::new("cargo")
            .args(["run", "--quiet", "--offline", "--locked"])
            .current_dir(directory.path())
            .env("CARGO_TARGET_DIR", directory.path().join("target"))
            .output()
            .context("Cannot execute the merged Rust program.")?;
        let stdout = String::from_utf8_lossy(&output.stdout);
        let result_ok = if behavior {
            stdout == "start,alpha,beta,end\n" || stdout == "start,beta,alpha,end\n"
        } else {
            stdout == "parcel\n"
        };
        check.require(
            output.status.success() && result_ok,
            format!("{channel} must produce the correct executable result. stdout={stdout:?}, stderr={:?}", String::from_utf8_lossy(&output.stderr)),
        );
    }
    Ok(())
}
